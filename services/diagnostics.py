COMPILED_RULES = [(rule, re.compile(rule["pattern"])) for rule in RULES]


def diagnose(text: str) -> Finding:
    """Одна проверяемая подсказка; неизвестный случай остаётся неизвестным."""
    for rule, pattern in COMPILED_RULES:
        if pattern.search(text):
            return Finding(rule_id=rule["id"], title=rule["title"], category=rule["category"], explanation=rule["explanation"], steps=rule["steps"], known_pattern=True)
    return Finding(
        rule_id="unknown", title="Нужен ручной разбор", category="Не определено",
        explanation="Подходящего правила пока нет. Исходные строки помогут воспроизвести случай и добавить новую проверенную подсказку.",
        steps=["Прочитай сообщение и первый относящийся к моду кадр стека.", "Запиши, какое действие вызвало сбой, и повтори его в тестовом запуске."],
        known_pattern=False,
    )
